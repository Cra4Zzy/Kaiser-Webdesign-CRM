BEGIN;

CREATE SCHEMA kaiser_crm;

REVOKE ALL ON SCHEMA kaiser_crm FROM PUBLIC, anon, authenticated;

SET LOCAL search_path TO kaiser_crm, pg_catalog;

CREATE TABLE crm_members (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name TEXT NOT NULL,active INTEGER NOT NULL DEFAULT 1);

CREATE TABLE companies (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            industry TEXT DEFAULT '', city TEXT DEFAULT '',
            phone TEXT DEFAULT '', email TEXT DEFAULT '', website TEXT DEFAULT '',
            website_status TEXT DEFAULT '', social_status TEXT DEFAULT '',
            source TEXT DEFAULT '', source_url TEXT DEFAULT '', notes TEXT DEFAULT '',
            created_at TEXT NOT NULL, updated_at TEXT NOT NULL
        , website_audit_json TEXT DEFAULT '{}', website_audit_at TEXT DEFAULT '', do_not_contact INTEGER NOT NULL DEFAULT 0);

CREATE INDEX idx_companies_name ON companies(name);

CREATE TABLE contacts (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            company_id BIGINT NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
            first_name TEXT DEFAULT '', last_name TEXT DEFAULT '', role TEXT DEFAULT '',
            phone TEXT DEFAULT '', email TEXT DEFAULT '', preferred_channel TEXT DEFAULT '',
            notes TEXT DEFAULT '', is_primary INTEGER DEFAULT 1,
            created_at TEXT NOT NULL, updated_at TEXT NOT NULL
        );

CREATE TABLE deals (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            company_id BIGINT NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
            contact_id BIGINT REFERENCES contacts(id) ON DELETE SET NULL,
            title TEXT NOT NULL, stage TEXT NOT NULL DEFAULT 'new',
            disposition TEXT NOT NULL DEFAULT 'active', do_not_contact INTEGER DEFAULT 0,
            disposition_at TEXT DEFAULT '',
            value DOUBLE PRECISION DEFAULT 0, score INTEGER DEFAULT 60, priority TEXT DEFAULT 'medium',
            source TEXT DEFAULT '', next_follow_up TEXT DEFAULT '', next_action TEXT DEFAULT '', last_contact TEXT DEFAULT '',
            need_summary TEXT DEFAULT '', notes TEXT DEFAULT '', lost_reason TEXT DEFAULT '',
            import_raw TEXT DEFAULT '{}',
            created_at TEXT NOT NULL, updated_at TEXT NOT NULL
        , research_json TEXT DEFAULT '{}', proposal_url TEXT DEFAULT '', proposal_sent_at TEXT DEFAULT '', next_follow_up_time TEXT DEFAULT '', owner_id BIGINT REFERENCES crm_members(id) ON DELETE SET NULL);

CREATE INDEX idx_deals_stage ON deals(stage);

CREATE INDEX idx_deals_disposition ON deals(disposition);

CREATE TABLE tasks (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            title TEXT NOT NULL, due_date TEXT DEFAULT '', priority TEXT DEFAULT 'medium',
            status TEXT DEFAULT 'open', company_id BIGINT REFERENCES companies(id) ON DELETE SET NULL,
            contact_id BIGINT REFERENCES contacts(id) ON DELETE SET NULL,
            deal_id BIGINT REFERENCES deals(id) ON DELETE SET NULL,
            notes TEXT DEFAULT '', created_at TEXT NOT NULL, updated_at TEXT NOT NULL
        , due_time TEXT DEFAULT '', owner_id BIGINT REFERENCES crm_members(id) ON DELETE SET NULL, kind TEXT NOT NULL DEFAULT 'task');

CREATE INDEX idx_tasks_due ON tasks(due_date);

CREATE TABLE appointments (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title TEXT NOT NULL,
        start_at TEXT NOT NULL, end_at TEXT NOT NULL, location TEXT DEFAULT '',
        kind TEXT NOT NULL DEFAULT 'meeting', status TEXT NOT NULL DEFAULT 'planned',
        reminder_minutes INTEGER NOT NULL DEFAULT 15, notes TEXT DEFAULT '',
        deal_id BIGINT REFERENCES deals(id) ON DELETE SET NULL,
        company_id BIGINT REFERENCES companies(id) ON DELETE SET NULL,
        created_at TEXT NOT NULL, updated_at TEXT NOT NULL, owner_id BIGINT REFERENCES crm_members(id) ON DELETE SET NULL);

CREATE INDEX idx_appointments_start ON appointments(start_at);

CREATE TABLE projects (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            company_id BIGINT NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
            deal_id BIGINT REFERENCES deals(id) ON DELETE SET NULL,
            name TEXT NOT NULL, status TEXT DEFAULT 'planning', value DOUBLE PRECISION DEFAULT 0,
            deadline TEXT DEFAULT '', domain TEXT DEFAULT '', repo_url TEXT DEFAULT '', notes TEXT DEFAULT '',
            created_at TEXT NOT NULL, updated_at TEXT NOT NULL
        , owner_id BIGINT REFERENCES crm_members(id) ON DELETE SET NULL);

CREATE TABLE activities (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            type TEXT NOT NULL DEFAULT 'note', subject TEXT DEFAULT '', body TEXT DEFAULT '',
            occurred_at TEXT NOT NULL, company_id BIGINT REFERENCES companies(id) ON DELETE CASCADE,
            contact_id BIGINT REFERENCES contacts(id) ON DELETE SET NULL,
            deal_id BIGINT REFERENCES deals(id) ON DELETE CASCADE,
            metadata TEXT DEFAULT '{}',
            undone_at TEXT DEFAULT '', undone_reason TEXT DEFAULT ''
        );

CREATE INDEX idx_activities_deal ON activities(deal_id, occurred_at);

CREATE INDEX idx_activities_deal_type ON activities(deal_id, type, occurred_at);

CREATE TABLE imports (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            filename TEXT NOT NULL, sheet_name TEXT DEFAULT '', total_rows INTEGER DEFAULT 0,
            imported_count INTEGER DEFAULT 0, duplicate_count INTEGER DEFAULT 0,
            excluded_count INTEGER DEFAULT 0, error_count INTEGER DEFAULT 0,
            report_json TEXT DEFAULT '{}', created_at TEXT NOT NULL
        );

CREATE TABLE settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);

CREATE TABLE agent_runs (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, started_at TEXT NOT NULL, finished_at TEXT DEFAULT '', status TEXT DEFAULT 'running',
            query TEXT DEFAULT '', found_count INTEGER DEFAULT 0, imported_count INTEGER DEFAULT 0, duplicate_count INTEGER DEFAULT 0, excluded_count INTEGER DEFAULT 0, report_json TEXT DEFAULT '{}'
        );

CREATE TABLE account_access (user_id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE, member_id BIGINT NOT NULL UNIQUE REFERENCES crm_members(id), role TEXT NOT NULL CHECK(role IN ('admin','staff')), active BOOLEAN NOT NULL DEFAULT true);

CREATE TABLE migration_state (id INTEGER PRIMARY KEY CHECK(id=1), imported_at TIMESTAMPTZ NOT NULL DEFAULT now());

ALTER TABLE crm_members ENABLE ROW LEVEL SECURITY;

ALTER TABLE companies ENABLE ROW LEVEL SECURITY;

ALTER TABLE contacts ENABLE ROW LEVEL SECURITY;

ALTER TABLE deals ENABLE ROW LEVEL SECURITY;

ALTER TABLE tasks ENABLE ROW LEVEL SECURITY;

ALTER TABLE appointments ENABLE ROW LEVEL SECURITY;

ALTER TABLE projects ENABLE ROW LEVEL SECURITY;

ALTER TABLE activities ENABLE ROW LEVEL SECURITY;

ALTER TABLE imports ENABLE ROW LEVEL SECURITY;

ALTER TABLE settings ENABLE ROW LEVEL SECURITY;

ALTER TABLE agent_runs ENABLE ROW LEVEL SECURITY;

ALTER TABLE account_access ENABLE ROW LEVEL SECURITY;

ALTER TABLE migration_state ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON ALL TABLES IN SCHEMA kaiser_crm FROM PUBLIC, anon, authenticated;

REVOKE ALL ON ALL SEQUENCES IN SCHEMA kaiser_crm FROM PUBLIC, anon, authenticated;

COMMIT;
