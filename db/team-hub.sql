
-- Kaiser CRM team collaboration: additive only (no changes to existing lead/customer data).
-- Executed with server-side Supabase secret via Cloudflare worker; never from browser.
create table if not exists kaiser_crm.team_messages (
 id bigint generated by default as identity primary key,
 user_id uuid not null,
 member_id bigint not null references kaiser_crm.crm_members(id),
 sender_name text not null,
 body text not null check (length(btrim(body)) between 1 and 1500),
 kind text not null default 'message' check (kind in ('message','system')),
 deal_id bigint references kaiser_crm.deals(id) on delete set null,
 company_id bigint references kaiser_crm.companies(id) on delete set null,
 created_at timestamptz not null default now()
);
create index if not exists idx_kaiser_team_messages_created on kaiser_crm.team_messages (id desc);
create index if not exists idx_kaiser_team_messages_deal on kaiser_crm.team_messages (deal_id, id desc);
alter table kaiser_crm.team_messages enable row level security;
revoke all on kaiser_crm.team_messages from public, anon, authenticated;
grant select, insert on kaiser_crm.team_messages to service_role;
grant usage, select on sequence kaiser_crm.team_messages_id_seq to service_role;

create table if not exists kaiser_crm.lead_claims (
 deal_id bigint primary key references kaiser_crm.deals(id) on delete cascade,
 user_id uuid not null,
 member_id bigint not null references kaiser_crm.crm_members(id),
 member_name text not null,
 purpose text not null default 'Lead bearbeiten' check (length(purpose) between 1 and 120),
 lease_until timestamptz not null,
 updated_at timestamptz not null default now()
);
create index if not exists idx_kaiser_lead_claims_expiry on kaiser_crm.lead_claims (lease_until);
alter table kaiser_crm.lead_claims enable row level security;
revoke all on kaiser_crm.lead_claims from public, anon, authenticated;
grant select, insert, update, delete on kaiser_crm.lead_claims to service_role;

create or replace function public.kaiser_team_hub_read(p_uid uuid, p_before bigint default null)
returns jsonb language plpgsql set search_path to 'pg_catalog','kaiser_crm' as $$
declare ident jsonb; messages jsonb; claims jsonb; more boolean;
begin
 ident:=kaiser_crm.pages_identity(p_uid);
 if ident is null then raise exception 'CRM_ACCESS_DENIED' using errcode='42501'; end if;
 select coalesce(jsonb_agg(to_jsonb(t) order by t.id),'[]'::jsonb)
 into messages from (
   select m.id,m.member_id,m.sender_name,m.body,m.kind,m.deal_id,m.company_id,m.created_at,
          coalesce(c.name,'') as company_name,coalesce(d.title,'') as deal_title
   from kaiser_crm.team_messages m
   left join kaiser_crm.deals d on d.id=m.deal_id
   left join kaiser_crm.companies c on c.id=coalesce(m.company_id,d.company_id)
   where p_before is null or m.id < p_before
   order by m.id desc limit 60
 ) t;
 select exists(
   select 1 from kaiser_crm.team_messages
   where (p_before is null or id < p_before)
   and id < coalesce((select min((z->>'id')::bigint) from jsonb_array_elements(messages) z),0)
 ) into more;
 select coalesce(jsonb_agg(jsonb_build_object(
   'deal_id',l.deal_id,'company_id',d.company_id,'member_id',l.member_id,
   'name',l.member_name,'purpose',l.purpose,'mine',l.user_id=p_uid,'lease_until',l.lease_until,
   'company_name',c.name,'deal_title',d.title
 ) order by l.updated_at desc),'[]'::jsonb)
 into claims from kaiser_crm.lead_claims l
 join kaiser_crm.deals d on d.id=l.deal_id
 join kaiser_crm.companies c on c.id=d.company_id
 where l.lease_until>now();
 return jsonb_build_object('messages',messages,'claims',claims,
   'has_older',coalesce(more,false),'member_id',(ident->>'member_id')::bigint);
end $$;
revoke all on function public.kaiser_team_hub_read(uuid,bigint) from public, anon, authenticated;
grant execute on function public.kaiser_team_hub_read(uuid,bigint) to service_role;

create or replace function public.kaiser_team_hub_send(p_uid uuid,p_body text,p_deal_id bigint default null)
returns jsonb language plpgsql set search_path to 'pg_catalog','kaiser_crm' as $$
declare ident jsonb; c_id bigint; msg jsonb;
begin
 ident:=kaiser_crm.pages_identity(p_uid);
 if ident is null then raise exception 'CRM_ACCESS_DENIED' using errcode='42501'; end if;
 if length(btrim(coalesce(p_body,''))) not between 1 and 1500
 then raise exception 'Nachricht muss 1 bis 1500 Zeichen enthalten.' using errcode='22023'; end if;
 if p_deal_id is not null then
  select company_id into c_id from kaiser_crm.deals where id=p_deal_id;
  if not found then raise exception 'Lead nicht gefunden.' using errcode='22023'; end if;
 end if;
 insert into kaiser_crm.team_messages(user_id,member_id,sender_name,body,kind,deal_id,company_id)
 values(p_uid,(ident->>'member_id')::bigint,ident->>'name',btrim(p_body),'message',p_deal_id,c_id)
 returning jsonb_build_object('id',id,'sender_name',sender_name,'body',body,'created_at',created_at,'deal_id',deal_id,'kind',kind) into msg;
 return msg;
end $$;
revoke all on function public.kaiser_team_hub_send(uuid,text,bigint) from public, anon, authenticated;
grant execute on function public.kaiser_team_hub_send(uuid,text,bigint) to service_role;

create or replace function public.kaiser_lead_claim(p_uid uuid,p_deal_id bigint,p_action text,p_purpose text default 'Lead bearbeiten')
returns jsonb language plpgsql set search_path to 'pg_catalog','kaiser_crm' as $$
declare ident jsonb; c_id bigint; l kaiser_crm.lead_claims%rowtype;
begin
 ident:=kaiser_crm.pages_identity(p_uid);
 if ident is null then raise exception 'CRM_ACCESS_DENIED' using errcode='42501'; end if;
 if p_action not in ('claim','release','renew') then raise exception 'Ungültige Aktion.' using errcode='22023'; end if;
 select company_id into c_id from kaiser_crm.deals where id=p_deal_id;
 if not found then raise exception 'Lead nicht gefunden.' using errcode='22023'; end if;
 if p_action='release' then
   delete from kaiser_crm.lead_claims where deal_id=p_deal_id and user_id=p_uid returning * into l;
   if not found then raise exception 'Der Lead ist nicht von dir reserviert.' using errcode='55P03'; end if;
   insert into kaiser_crm.team_messages(user_id,member_id,sender_name,body,kind,deal_id,company_id)
   values(p_uid,(ident->>'member_id')::bigint,ident->>'name','hat die Bearbeitung freigegeben.','system',p_deal_id,c_id);
   return jsonb_build_object('ok',true,'released',true);
 end if;
 if p_action='renew' then
   update kaiser_crm.lead_claims set lease_until=now()+interval '20 minutes',updated_at=now()
   where deal_id=p_deal_id and user_id=p_uid and lease_until>now() returning * into l;
   if not found then raise exception 'Bearbeitungsreservierung ist abgelaufen.' using errcode='55P03'; end if;
 else
   if length(btrim(coalesce(p_purpose,''))) not between 1 and 120
   then raise exception 'Tätigkeit muss 1 bis 120 Zeichen enthalten.' using errcode='22023'; end if;
   insert into kaiser_crm.lead_claims(deal_id,user_id,member_id,member_name,purpose,lease_until)
   values(p_deal_id,p_uid,(ident->>'member_id')::bigint,ident->>'name',btrim(p_purpose),now()+interval '20 minutes')
   on conflict (deal_id) do update
   set user_id=excluded.user_id,member_id=excluded.member_id,member_name=excluded.member_name,
       purpose=excluded.purpose,lease_until=excluded.lease_until,updated_at=now()
   where lead_claims.user_id=excluded.user_id or lead_claims.lease_until<=now()
   returning * into l;
   if not found then raise exception 'Lead wird bereits von einem Teammitglied bearbeitet.' using errcode='55P03'; end if;
   insert into kaiser_crm.team_messages(user_id,member_id,sender_name,body,kind,deal_id,company_id)
   values(p_uid,(ident->>'member_id')::bigint,ident->>'name','arbeitet an: '||l.purpose,'system',p_deal_id,c_id);
 end if;
 return jsonb_build_object('ok',true,'deal_id',l.deal_id,'member_id',l.member_id,
   'name',l.member_name,'purpose',l.purpose,'mine',true,'lease_until',l.lease_until);
end $$;
revoke all on function public.kaiser_lead_claim(uuid,bigint,text,text) from public, anon, authenticated;
grant execute on function public.kaiser_lead_claim(uuid,bigint,text,text) to service_role;

create or replace function public.kaiser_lead_lock_check(p_uid uuid,p_deal_id bigint default null,p_company_id bigint default null)
returns jsonb language plpgsql stable set search_path to 'pg_catalog','kaiser_crm' as $$
declare ident jsonb; l record;
begin
 ident:=kaiser_crm.pages_identity(p_uid);
 if ident is null then raise exception 'CRM_ACCESS_DENIED' using errcode='42501'; end if;
 select lc.member_name,lc.purpose into l
 from kaiser_crm.lead_claims lc
 join kaiser_crm.deals d on d.id=lc.deal_id
 where lc.lease_until>now() and lc.user_id<>p_uid
   and (lc.deal_id=p_deal_id or (p_company_id is not null and d.company_id=p_company_id))
 limit 1;
 if found then
   return jsonb_build_object('allowed',false,'name',l.member_name,'purpose',l.purpose);
 end if;
 return jsonb_build_object('allowed',true);
end $$;
revoke all on function public.kaiser_lead_lock_check(uuid,bigint,bigint) from public, anon, authenticated;
grant execute on function public.kaiser_lead_lock_check(uuid,bigint,bigint) to service_role;
